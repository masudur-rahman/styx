// Patient uses styx.UUID, whose Go type alone selects a native uuid column.
// The tag carries only pk.
type Patient struct {
	ID   styx.UUID `db:"id,pk"`
	Name string    `db:"name"`
}

// Example_uuidColumn shows styx.UUID as a primary key. A plain string field
// reaches the same column type with `db:"id,pk type=uuid"` instead.
func Example_uuidColumn() {
	db := openDB()
	db.Sync(ctx, Patient{})

	p := &Patient{ID: "6ba7b810-9dad-11d1-80b4-00c04fd430c8", Name: "Ada"}
	db.Table("patient").InsertOne(ctx, p)

	var got Patient
	db.Table("patient").ID(p.ID).FindOne(ctx, &got)

	fmt.Println("id:", got.ID)
	fmt.Println("name:", got.Name)

	// Output:
	// id: 6ba7b810-9dad-11d1-80b4-00c04fd430c8
	// name: Ada
}

// CSV packs a string slice into one column. A type implementing sql.Scanner
// and driver.Valuer handles its own reading and writing, so it needs no tag.
type CSV []string

func (c *CSV) Scan(src any) error {
	s, ok := src.(string)
	if !ok || s == "" {
		*c = nil
		return nil
	}
	*c = strings.Split(s, ",")
	return nil
}

func (c CSV) Value() (driver.Value, error) { return strings.Join(c, ","), nil }

var _ sql.Scanner = (*CSV)(nil)

type TaggedPost struct {
	ID   int64  `db:"id,pk autoincr"`
	Name string `db:"name"`
	Tags CSV    `db:"tags"`
}

// Example_scannerColumn shows a column type implementing sql.Scanner.
func Example_scannerColumn() {
	db := openDB()
	db.Sync(ctx, TaggedPost{})

	p := &TaggedPost{Name: "styx", Tags: CSV{"go", "orm", "sql"}}
	db.Table("tagged_post").InsertOne(ctx, p)

	var got TaggedPost
	db.Table("tagged_post").ID(p.ID).FindOne(ctx, &got)

	fmt.Println("name:", got.Name)
	fmt.Println("tags:", got.Tags)

	// Output:
	// name: styx
	// tags: [go orm sql]
}

