// Money is a caller's own type, mapped to a column type by RegisterSQLType.
type Money int64

func init() {
	styx.RegisterSQLType(reflect.TypeOf(Money(0)), map[string]string{
		styx.DialectPostgres: "NUMERIC(19,4)",
		styx.DialectSQLite:   "REAL",
	})
}

// Meta is stored as a single JSON column.
type Meta struct {
	Source string `json:"source"`
}

// Auditable is embedded below. Embedding flattens its fields into the outer
// table, so every table can share bookkeeping columns without repeating them.
type Auditable struct {
	CreatedAt time.Time  `db:"created_at"`
	CreatedBy string     `db:"created_by"`
	DeletedAt *time.Time `db:"deleted_at,archive"`
}

// Ledger uses every db tag styx understands. The column name comes before the
// comma; the options after it are separated by spaces, never commas.
type Ledger struct {
	// pk + autoincr: primary key, generated by the database.
	ID int64 `db:"id,pk autoincr"`

	// type=: names the column type outright. Portable names such as uuid map
	// per dialect; anything else is passed through as literal SQL.
	OwnerID string `db:"owner_id,type=uuid"`
	Ref     string `db:"ref,type=varchar(32)"`

	// styx.UUID reaches a native uuid column through its Go type, no tag.
	BatchID styx.UUID `db:"batch_id"`

	// Registered custom type.
	Amount Money `db:"amount"`

	// uq: single-column unique. notnull: NOT NULL.
	Code  string `db:"code,uq"`
	Title string `db:"title,notnull"`

	// uqs: every uqs field joins one composite UNIQUE(...).
	Tenant string `db:"tenant,uqs"`
	Period string `db:"period,uqs"`

	// req: always written, even when zero. Without it a zero value is skipped.
	Revision int `db:"revision,req"`

	// idx / uidx: single-column index. Add ":name" to combine fields into one
	// multi-column index.
	Status   string `db:"status,idx"`
	Email    string `db:"email,uidx"`
	Region   string `db:"region,idx:region_zone"`
	Zone     string `db:"zone,idx:region_zone"`
	Sequence int    `db:"sequence,uidx:tenant_seq"`

	// json: any struct, map or slice stored as a JSON column.
	Meta Meta `db:"meta,json"`

	// Empty column name: derived from the field name as snake_case.
	FullName string `db:",notnull"`

	// "-": never a column. Not written, read, or scanned.
	Scratch string `db:"-"`

	// archive and the audit columns arrive through the embed.
	Auditable
}

// Example_structTags exercises every db tag on one struct.
func Example_structTags() {
	db := openDB()
	if err := db.Sync(ctx, Ledger{}); err != nil {
		fmt.Println("sync failed:", err)
		return
	}

	l := &Ledger{
		OwnerID: "6ba7b810-9dad-11d1-80b4-00c04fd430c8",
		Ref:     "LDG-1",
		BatchID: "0b6dd39a-2f83-4a30-9f3c-2f4d0f0a1b2c",
		Amount:  1999,
		Code:    "AC-1",
		Title:   "opening balance",
		Tenant:  "acme",
		Period:  "2026-08",
		Status:  "open",
		Email:   "ops@acme.test",
		Region:  "apac",
		Zone:    "a",
		Meta:    Meta{Source: "import"},

		FullName: "Acme Opening Balance",
		Scratch:  "never stored",
	}
	l.CreatedBy = "masud"
	l.CreatedAt = time.Date(2026, 8, 21, 9, 0, 0, 0, time.UTC)

	if _, err := db.Table("ledger").InsertOne(ctx, l); err != nil {
		fmt.Println("insert failed:", err)
		return
	}

	var got Ledger
	db.Table("ledger").ID(l.ID).FindOne(ctx, &got)

	fmt.Println("owner:", got.OwnerID)
	fmt.Println("batch:", got.BatchID)
	fmt.Println("amount:", got.Amount)
	fmt.Println("title:", got.Title)
	fmt.Println("meta source:", got.Meta.Source)
	fmt.Println("full name:", got.FullName)
	fmt.Println("created by:", got.CreatedBy)
	fmt.Println("scratch persisted:", got.Scratch != "")

	// req means Revision is written even at zero, so a second row with the
	// same tenant and period trips the composite unique constraint.
	_, err := db.Table("ledger").InsertOne(ctx, &Ledger{
		Code: "AC-2", Title: "dup", Tenant: "acme", Period: "2026-08",
	})
	fmt.Println("composite unique enforced:", err != nil)

	// notnull rejects a missing value.
	_, err = db.Table("ledger").InsertOne(ctx, &Ledger{Code: "AC-3"})
	fmt.Println("notnull enforced:", err != nil)

	// archive: DeleteOne marks the row instead of removing it.
	db.Table("ledger").ID(l.ID).DeleteOne(ctx)
	found, _ := db.Table("ledger").ID(l.ID).FindOne(ctx, &Ledger{})
	fmt.Println("found after delete:", found)

	// Output:
	// owner: 6ba7b810-9dad-11d1-80b4-00c04fd430c8
	// batch: 0b6dd39a-2f83-4a30-9f3c-2f4d0f0a1b2c
	// amount: 1999
	// title: opening balance
	// meta source: import
	// full name: Acme Opening Balance
	// created by: masud
	// scratch persisted: false
	// composite unique enforced: true
	// notnull enforced: true
	// found after delete: false
}

