// Article embeds Auditable, so it gets created_at, created_by and deleted_at
// without repeating them. Tags are found through the embed too, so archive
// still drives soft delete.
type Article struct {
	ID    int64  `db:"id,pk autoincr"`
	Title string `db:"title"`
	Auditable
}

// Example_embeddedStruct shows an embedded struct flattened into columns.
func Example_embeddedStruct() {
	db := openDB()
	db.Sync(ctx, Article{})

	a := &Article{Title: "styx v2"}
	a.CreatedBy = "masud"
	a.CreatedAt = time.Date(2026, 8, 21, 9, 0, 0, 0, time.UTC)
	db.Table("article").InsertOne(ctx, a)

	var got Article
	db.Table("article").ID(a.ID).FindOne(ctx, &got)

	fmt.Println("title:", got.Title)
	fmt.Println("created by:", got.CreatedBy)
	fmt.Println("created at:", got.CreatedAt.Format("2006-01-02"))

	db.Table("article").ID(a.ID).DeleteOne(ctx)
	found, _ := db.Table("article").ID(a.ID).FindOne(ctx, &Article{})
	fmt.Println("found after delete:", found)

	// Output:
	// title: styx v2
	// created by: masud
	// created at: 2026-08-21
	// found after delete: false
}

// Timestamped shows shadowing: a field on the outer struct hides one of the
// same column name from the embed, matching Go's own rule.
type Timestamped struct {
	ID        int64  `db:"id,pk autoincr"`
	CreatedBy string `db:"created_by,notnull"`
	Auditable
}

// Example_embeddedShadowing shows an outer field overriding an embedded one.
func Example_embeddedShadowing() {
	db := openDB()
	db.Sync(ctx, Timestamped{})

	row := &Timestamped{CreatedBy: "outer"}
	db.Table("timestamped").InsertOne(ctx, row)

	var got Timestamped
	db.Table("timestamped").ID(row.ID).FindOne(ctx, &got)

	fmt.Println("created by:", got.CreatedBy)
	fmt.Println("embedded field is empty:", got.Auditable.CreatedBy == "")

	// Output:
	// created by: outer
	// embedded field is empty: true
}

// Relations are declared with their own tags. The column part is "-" because
// the field holds related entities rather than a column of this table.
type TagAuthor struct {
	ID    int64      `db:"id,pk autoincr"`
	Name  string     `db:"name"`
	Books []TagBook  `db:"-,o2m fk:author_id"`
	Tags  []TagLabel `db:"-,m2m join:author_labels fk:author_id ref:label_id"`
}

type TagBook struct {
	ID       int64      `db:"id,pk autoincr"`
	AuthorID int64      `db:"author_id"`
	Author   *TagAuthor `db:"-,m2o fk:author_id"`
}

type TagLabel struct {
	ID   int64  `db:"id,pk autoincr"`
	Name string `db:"name"`
}

// Example_relationTags lists the association tags. o2m and m2m sit on the
// parent, m2o on the child holding the foreign key.
func Example_relationTags() {
	for _, f := range []string{
		`Books []TagBook  ` + "`" + `db:"-,o2m fk:author_id"` + "`",
		`Author *TagAuthor ` + "`" + `db:"-,m2o fk:author_id"` + "`",
		`Tags  []TagLabel ` + "`" + `db:"-,m2m join:author_labels fk:author_id ref:label_id"` + "`",
	} {
		fmt.Println(f)
	}

	// Output:
	// Books []TagBook  `db:"-,o2m fk:author_id"`
	// Author *TagAuthor `db:"-,m2o fk:author_id"`
	// Tags  []TagLabel `db:"-,m2m join:author_labels fk:author_id ref:label_id"`
}

// BadTags misuses the tag two ways: attributes are separated by spaces, not
// commas, and uqq is not an option. Both used to be dropped in silence, so the
// table came out with no primary key and no unique constraint.
type BadTags struct {
	ID    int64  `db:"id,pk,uq"`
	Email string `db:"email,uqq"`
}

// Example_tagValidation shows Sync rejecting malformed db tags.
func Example_tagValidation() {
	db := openDB()

	err := db.Sync(ctx, BadTags{})
	msg := fmt.Sprint(err)

	fmt.Println("rejected:", err != nil)
	fmt.Println("names the comma:", strings.Contains(msg, "separated by spaces"))
	fmt.Println("names the typo:", strings.Contains(msg, `unknown option "UQQ"`))
	fmt.Println("reports both fields:",
		strings.Contains(msg, "field ID") && strings.Contains(msg, "field Email"))

	// Output:
	// rejected: true
	// names the comma: true
	// names the typo: true
	// reports both fields: true
}
